def create_po_file(locale: str, translations: Dict[str, str]):
    """Create a PO file for a specific locale with translations."""

    # Create locale directory structure
    locale_dir = Path(__file__).parent.parent / 'ocular' / 'locales' / locale / 'LC_MESSAGES'
    locale_dir.mkdir(parents=True, exist_ok=True)

    po_file = locale_dir / 'messages.po'

    # PO file header
    header = f"""# {locale} translations for Ocular OCR Service
# Copyright (C) 2024 Ocular OCR
# This file is distributed under the same license as the Ocular package.
#
msgid ""
msgstr ""
"Project-Id-Version: Ocular OCR 0.1.0\\n"
"Report-Msgid-Bugs-To: \\n"
"POT-Creation-Date: 2025-10-06 10:00+0000\\n"
"PO-Revision-Date: 2025-10-06 10:00+0000\\n"
"Last-Translator: Ocular Team\\n"
"Language: {locale}\\n"
"Language-Team: {locale}\\n"
"MIME-Version: 1.0\\n"
"Content-Type: text/plain; charset=UTF-8\\n"
"Content-Transfer-Encoding: 8bit\\n"

"""

    # Add translations
    content = header
    for msgid, msgstr in translations.items():
        # Escape quotes in strings
        msgid_escaped = msgid.replace('"', '\\"')
        msgstr_escaped = msgstr.replace('"', '\\"')

        content += f'msgid "{msgid_escaped}"\n'
        content += f'msgstr "{msgstr_escaped}"\n\n'

    # Write PO file
    with open(po_file, 'w', encoding='utf-8') as f:
        f.write(content)

    print(f"✅ Created {locale}/LC_MESSAGES/messages.po with {len(translations)} translations")

    return po_file


def main():
    """Generate all translation files."""
    print("🌐 Generating translation files for Ocular OCR Service\n")

    for locale, translations in TRANSLATIONS.items():
        create_po_file(locale, translations)

    print(f"\n🎉 Generated translation files for {len(TRANSLATIONS)} languages!")
    print("\n📝 Next steps:")
    print("   1. Review the generated PO files in ocular/locales/")
    print("   2. Compile translations: pybabel compile -d ocular/locales")
    print("   3. Restart your application to load translations")
    print("\n💡 To add more translations:")
    print("   - Edit the TRANSLATIONS dictionary in this script")
    print("   - Or use DeepL API: python3 scripts/translate_with_deepl.py")


if __name__ == '__main__':
    main()
